"""Export the saved evaluation runs for the browser playground (docs/index.html).

    uv run python eval/export_playground.py

Writes docs/playground-data.js. The playground replays the decider's recorded answers and
runs the cost-table policy in the browser, so it needs no server and no model.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "patterns" / "memory_gate"))
sys.path.insert(0, str(ROOT / "eval"))

import run_eval as ev  # noqa: E402
from memory_gate import COST, LABELS  # noqa: E402

GATES = {  # set: (scenarios, saved gate run)
    "original": ("eval/scenarios.json", "eval/results/run-20261021-202009.json"),
    "fresh": ("eval/fresh_scenarios.json", "eval/results/run-20261022-001433.json"),
}
REPLIES = "eval/results/run-20261021-205552.json"  # the 34 original scenarios, replies by Qwen2.5 3B
OUT = ROOT / "docs" / "playground-data.js"


def read(path: str):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def main() -> None:
    replies = {r["id"]: r["systems"] for r in read(REPLIES)}
    scenarios = []
    for set_name, (scenario_file, run_file) in GATES.items():
        runs = {r["id"]: r for r in read(run_file)}
        for s in read(scenario_file):
            run = runs[s["id"]]
            tact = run["systems"]["tact"]["gate"]
            item = {"id": s["id"], "set": set_name, "dev": s["id"] in ev.DEV, "flip": bool(s.get("flip")),
                    "message": s["message"], "history": s.get("history", []),
                    "candidates": run["candidates"],
                    "labels": {mid: ev.label_of(s, mid) for mid in run["candidates"]},
                    "p": {mid: [tact[mid]["p"][k] for k in LABELS] for mid in run["candidates"]},
                    "llm": {mid: v["action"] for mid, v in run["systems"]["llm_gate"]["gate"].items()}}
            if s["id"] in replies:
                item["replies"] = {k: {"text": replies[s["id"]][k]["reply"],
                                       "leaks": ev.keyword_leaks(replies[s["id"]][k]["reply"], s),
                                       "tokens": replies[s["id"]][k]["input_tokens"]}
                                   for k in ("all", "rag", "tact")}
            scenarios.append(item)
    data = {"cost": COST, "memories": {m["id"]: m["text"] for m in read("data/memories.json")},
            "sensitive": ev.SENSITIVE, "scenarios": scenarios,
            "sources": {"gates": [run for _, run in GATES.values()], "replies": REPLIES,
                        "reply_model": "Qwen2.5 3B (Ollama on the decider's EC2 instance)",
                        "llm_gate_model": "Qwen2.5 3B"}}
    OUT.write_text("// Generated by eval/export_playground.py from the saved evaluation runs.\n"
                   "window.TACT = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
                   encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(scenarios)} scenarios, {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
